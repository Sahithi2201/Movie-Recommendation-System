#Import required libraries

import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

print("All libraries imported successfully!")

# Create the movie dataset

movies = {
    "title": [
        "The Space Journey",
        "Galaxy Mission",
        "Laugh Out Loud",
        "The Funny Neighbors",
        "Mystery at Midnight",
        "Detective's Secret",
        "Love in Spring",
        "A Heart's Promise",
        "The Final Battle",
        "Wild Planet",
        "Haunted House",
        "The Last Survivor",
        "Family Weekend",
        "Beyond the Stars",
        "Courtroom Truth"
    ],
    "genres": [
        "science fiction adventure space",
        "science fiction action space",
        "comedy friendship",
        "comedy family friendship",
        "mystery thriller crime",
        "mystery crime drama",
        "romance drama",
        "romance comedy",
        "action adventure",
        "adventure nature documentary",
        "horror mystery",
        "thriller action",
        "family comedy",
        "science fiction drama space",
        "drama mystery"
    ]
}

df = pd.DataFrame(movies)

print("Movie dataset created successfully!")
print("\nFirst five movies:")
print(df.head())

print("\nTotal movies:", len(df))

#  Convert genres into numerical features

# Create the TF-IDF vectorizer
tfidf = TfidfVectorizer()

# Convert genre descriptions into numerical vectors
genre_matrix = tfidf.fit_transform(df["genres"])

# Calculate similarity between every pair of movies
similarity_matrix = cosine_similarity(genre_matrix)

print("Genre features created successfully!")
print("Number of movies:", genre_matrix.shape[0])
print("Number of genre features:", genre_matrix.shape[1])
print("\nSimilarity matrix shape:", similarity_matrix.shape)

#  Create the movie recommendation function

def recommend_movies(movie_title, number_of_recommendations=5):
    # Find the selected movie
    matches = df.index[
        df["title"].str.lower() == movie_title.lower()
    ].tolist()

    if not matches:
        print("Movie not found. Please check the title.")
        return

    movie_index = matches[0]

    # Get similarity scores for the selected movie
    scores = list(enumerate(similarity_matrix[movie_index]))

    # Remove the selected movie itself
    scores = [
        item for item in scores
        if item[0] != movie_index
    ]

    # Sort by similarity, highest first
    scores = sorted(
        scores,
        key=lambda item: item[1],
        reverse=True
    )

    print(f"Movies similar to '{movie_title}':\n")

    for index, score in scores[:number_of_recommendations]:
        print(f"{df.iloc[index]['title']} (similarity: {score:.2f})")


print("Recommendation function created successfully!")

recommend_movies("The Space Journey")

recommend_movies("Laugh Out Loud")